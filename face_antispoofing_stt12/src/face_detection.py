"""
Face Detection and Bounding Box Utilities
Supports MSU-MFSD .face annotation parsing and OpenCV Haar/DNN detection for realtime inference.
Author: Team STT 12
"""

import os
from pathlib import Path
from typing import Dict, List, Tuple, Optional
import cv2
import numpy as np


class FaceAnnotationReader:
    """
    Parses MSU-MFSD .face annotations generated by PittPatt SDK.
    Line format: frame_idx, left, top, right, bottom, x_left_eye, y_left_eye, x_right_eye, y_right_eye
    """

    def __init__(self, face_file_path: str):
        self.face_file_path = Path(face_file_path)
        self.annotations: Dict[int, Tuple[int, int, int, int]] = {}
        self.landmarks: Dict[int, Tuple[float, float, float, float]] = {}
        self._load()

    def _load(self):
        if not self.face_file_path.exists():
            return

        with open(self.face_file_path, "r", encoding="utf-8") as f:
            for line in f:
                parts = [p.strip() for p in line.strip().split(",") if p.strip()]
                if len(parts) >= 5:
                    try:
                        f_idx = int(parts[0])
                        left = int(float(parts[1]))
                        top = int(float(parts[2]))
                        right = int(float(parts[3]))
                        bottom = int(float(parts[4]))
                        self.annotations[f_idx] = (left, top, right, bottom)

                        if len(parts) >= 9:
                            lx, ly, rx, ry = float(parts[5]), float(parts[6]), float(parts[7]), float(parts[8])
                            self.landmarks[f_idx] = (lx, ly, rx, ry)
                    except ValueError:
                        continue

    def get_bbox(self, frame_idx: int) -> Optional[Tuple[int, int, int, int]]:
        """Returns (left, top, right, bottom) for frame_idx, or closest annotated frame."""
        if frame_idx in self.annotations:
            return self.annotations[frame_idx]

        # If exact frame not found (PittPatt may skip <1% frames), fallback to nearest frame
        if self.annotations:
            closest_idx = min(self.annotations.keys(), key=lambda k: abs(k - frame_idx))
            if abs(closest_idx - frame_idx) <= 5:
                return self.annotations[closest_idx]
        return None


class FaceDetector:
    """
    Detector for live webcam feed or unannotated video frames.
    Uses OpenCV's Haar Cascade classifier with automatic fallback.
    """

    def __init__(self, min_size: Tuple[int, int] = (60, 60), scale_factor: float = 1.1, min_neighbors: int = 5):
        self.min_size = min_size
        self.scale_factor = scale_factor
        self.min_neighbors = min_neighbors

        # Check candidates for Haar cascade file
        local_model_path = Path(__file__).resolve().parent.parent / "models" / "haarcascade_frontalface_default.xml"
        cv2_path = Path(getattr(cv2.data, "haarcascades", "")) / "haarcascade_frontalface_default.xml"

        cascade_path = None
        for cand in [local_model_path, cv2_path]:
            if cand.exists():
                cascade_path = str(cand)
                break

        if cascade_path is None or not os.path.exists(cascade_path):
            # Graceful warning if detector file is not found
            self.detector = None
        else:
            self.detector = cv2.CascadeClassifier(cascade_path)

    def detect_faces(self, image: np.ndarray) -> List[Tuple[int, int, int, int, float]]:
        """
        Detects faces in BGR/RGB image.
        returns: list of (left, top, right, bottom, confidence_score)
        """
        if image is None or image.size == 0 or self.detector is None:
            return []

        if image.ndim == 3:
            gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
        else:
            gray = image

        # Equalize histogram for illumination robustness
        gray_eq = cv2.equalizeHist(gray)

        faces = self.detector.detectMultiScale(
            gray_eq,
            scaleFactor=self.scale_factor,
            minNeighbors=self.min_neighbors,
            minSize=self.min_size,
            flags=cv2.CASCADE_SCALE_IMAGE
        )

        results = []
        for (x, y, w, h) in faces:
            left = int(x)
            top = int(y)
            right = int(x + w)
            bottom = int(y + h)
            results.append((left, top, right, bottom, 1.0))

        # Sort by bounding box area descending (largest face first)
        results.sort(key=lambda b: (b[2] - b[0]) * (b[3] - b[1]), reverse=True)
        return results


def crop_face_with_margin(
    image: np.ndarray,
    bbox: Tuple[int, int, int, int],
    margin_ratio: float = 0.15,
    target_size: Tuple[int, int] = (224, 224)
) -> Tuple[Optional[np.ndarray], Tuple[int, int, int, int]]:
    """
    Crops face region with contextual boundary margin to retain anti-spoofing cues
    (such as display edges, reflections, photo print margins).
    bbox: (left, top, right, bottom)
    returns: (cropped_and_resized_image, expanded_bbox_coordinates)
    """
    H, W = image.shape[:2]
    left, top, right, bottom = bbox

    bw = right - left
    bh = bottom - top

    if bw <= 0 or bh <= 0:
        return None, (0, 0, 0, 0)

    # Expand by margin_ratio
    margin_x = int(bw * margin_ratio)
    margin_y = int(bh * margin_ratio)

    crop_x1 = max(0, left - margin_x)
    crop_y1 = max(0, top - margin_y)
    crop_x2 = min(W, right + margin_x)
    crop_y2 = min(H, bottom + margin_y)

    face_crop = image[crop_y1:crop_y2, crop_x1:crop_x2]
    if face_crop.size == 0:
        return None, (crop_x1, crop_y1, crop_x2, crop_y2)

    resized_face = cv2.resize(face_crop, target_size, interpolation=cv2.INTER_AREA)
    return resized_face, (crop_x1, crop_y1, crop_x2, crop_y2)
